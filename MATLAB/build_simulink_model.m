function build_simulink_model()
% BUILD_SIMULINK_MODEL Programmatically creates UnderwaterHideAndSeek.slx in Simulink.
%   Creates a modular closed-loop 6-DOF Hide-and-Seek Simulink model with:
%   - Seeker_AUV_6DOF (Controller + Fossen 6-DOF Dynamics)
%   - Hider_AUV_6DOF (Evasion AI + Fossen 6-DOF Dynamics)
%   - Sonar_and_EKF_Tracker (Acoustic Sonar + 3D EKF)
%   - Capture_Monitor (Distance, Capture Stop Logic, Scopes)

    modelName = 'UnderwaterHideAndSeek';
    rootDir = fileparts(mfilename('fullpath'));
    slxPath = fullfile(rootDir, [modelName '.slx']);

    if bdIsLoaded(modelName)
        close_system(modelName, 0);
    end
    if exist(slxPath, 'file')
        delete(slxPath);
    end

    new_system(modelName);
    open_system(modelName);

    % Configure fixed-step discrete/ode solver (dt = 0.05s, StopTime = 90s)
    set_param(modelName, 'SolverType', 'Fixed-step', ...
                         'Solver', 'FixedStepDiscrete', ...
                         'FixedStep', '0.05', ...
                         'StopTime', '90.0');

    % Add Clock
    add_block('simulink/Sources/Clock', [modelName '/SimTime'], 'Position', [40, 120, 70, 150]);

    % Add Seeker Dynamics & AI MATLAB Function block
    seekerBlk = [modelName '/Seeker_6DOF_AUV'];
    add_block('simulink/User-Defined Functions/MATLAB Function', seekerBlk, 'Position', [280, 70, 440, 170]);
    set_ml_fcn(seekerBlk, seeker_fcn_code());

    % Add Hider Dynamics & Evasion MATLAB Function block
    hiderBlk = [modelName '/Hider_6DOF_AUV'];
    add_block('simulink/User-Defined Functions/MATLAB Function', hiderBlk, 'Position', [280, 230, 440, 330]);
    set_ml_fcn(hiderBlk, hider_fcn_code());

    % Add Unit Delays for state feedback (12-element state [eta; nu])
    add_block('simulink/Discrete/Unit Delay', [modelName '/SeekerStateDelay'], ...
              'Position', [340, 185, 380, 215], 'Orientation', 'left', ...
              'InitialCondition', mat2str([30; 30; -10; 0; 0; -2.35; zeros(6,1)]));
    add_block('simulink/Discrete/Unit Delay', [modelName '/HiderStateDelay'], ...
              'Position', [340, 355, 380, 385], 'Orientation', 'left', ...
              'InitialCondition', mat2str([-12; -10; -14; 0; 0; 0.5; zeros(6,1)]));

    % Add Sonar + EKF Tracker MATLAB Function block
    ekfBlk = [modelName '/Sonar_and_EKF_Tracker'];
    add_block('simulink/User-Defined Functions/MATLAB Function', ekfBlk, 'Position', [520, 150, 680, 250]);
    set_ml_fcn(ekfBlk, ekf_fcn_code());

    add_block('simulink/Discrete/Unit Delay', [modelName '/EKFDelay'], ...
              'Position', [580, 275, 620, 305], 'Orientation', 'left', ...
              'InitialCondition', mat2str([-10; -10; -14; 0; 0; 0]));

    % Add Capture Monitor & Distance Calculation
    capBlk = [modelName '/Capture_Monitor'];
    add_block('simulink/User-Defined Functions/MATLAB Function', capBlk, 'Position', [740, 150, 880, 250]);
    set_ml_fcn(capBlk, capture_fcn_code());

    % Sinks: Scopes + Stop Simulation
    add_block('simulink/Sinks/Scope', [modelName '/Distance_Scope'], 'Position', [950, 140, 990, 180]);
    add_block('simulink/Sinks/Stop Simulation', [modelName '/Capture_Stop'], 'Position', [950, 210, 990, 250]);

    % Wire connections
    add_line(modelName, 'SimTime/1', 'Seeker_6DOF_AUV/1', 'autorouting', 'on');
    add_line(modelName, 'SeekerStateDelay/1', 'Seeker_6DOF_AUV/2', 'autorouting', 'on');
    add_line(modelName, 'EKFDelay/1', 'Seeker_6DOF_AUV/3', 'autorouting', 'on');
    add_line(modelName, 'Seeker_6DOF_AUV/1', 'SeekerStateDelay/1', 'autorouting', 'on');

    add_line(modelName, 'SimTime/1', 'Hider_6DOF_AUV/1', 'autorouting', 'on');
    add_line(modelName, 'HiderStateDelay/1', 'Hider_6DOF_AUV/2', 'autorouting', 'on');
    add_line(modelName, 'SeekerStateDelay/1', 'Hider_6DOF_AUV/3', 'autorouting', 'on');
    add_line(modelName, 'Hider_6DOF_AUV/1', 'HiderStateDelay/1', 'autorouting', 'on');

    add_line(modelName, 'Seeker_6DOF_AUV/1', 'Sonar_and_EKF_Tracker/1', 'autorouting', 'on');
    add_line(modelName, 'Hider_6DOF_AUV/1', 'Sonar_and_EKF_Tracker/2', 'autorouting', 'on');
    add_line(modelName, 'EKFDelay/1', 'Sonar_and_EKF_Tracker/3', 'autorouting', 'on');
    add_line(modelName, 'Sonar_and_EKF_Tracker/1', 'EKFDelay/1', 'autorouting', 'on');

    add_line(modelName, 'SimTime/1', 'Capture_Monitor/1', 'autorouting', 'on');
    add_line(modelName, 'Seeker_6DOF_AUV/1', 'Capture_Monitor/2', 'autorouting', 'on');
    add_line(modelName, 'Hider_6DOF_AUV/1', 'Capture_Monitor/3', 'autorouting', 'on');

    add_line(modelName, 'Capture_Monitor/1', 'Distance_Scope/1', 'autorouting', 'on');
    add_line(modelName, 'Capture_Monitor/2', 'Capture_Stop/1', 'autorouting', 'on');

    save_system(modelName, slxPath);
    fprintf('Simulink model saved to: %s\n', slxPath);
end

function set_ml_fcn(blkPath, codeStr)
    rt = sfroot();
    ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', blkPath);
    ch.Script = codeStr;
end

function s = seeker_fcn_code()
    s = sprintf([ ...
        'function state_next = stepSeeker(t, state_prev, ekf_est)\n' ...
        '%% 6-DOF Seeker Guidance + PID + Fossen Hydrodynamics (dt = 0.05s)\n' ...
        'dt = 0.05;\n' ...
        'eta = state_prev(1:6); nu = state_prev(7:12);\n' ...
        'p = eta(1:3); target = ekf_est(1:3);\n' ...
        'if t < 8.0\n' ...
        '    v_des = [0; 0; 0];\n' ...
        'else\n' ...
        '    diff_t = target - p;\n' ...
        '    n = norm(diff_t);\n' ...
        '    if n > 1e-3, v_des = (diff_t / n) * 2.0; else, v_des = [0;0;0]; end\n' ...
        'end\n' ...
        '%% Simple 6-DOF Fossen damping + proportional thrust\n' ...
        'M = diag([17.0, 24.2, 26.07, 0.28, 0.28, 0.40]);\n' ...
        'D = diag([4.03, 6.22, 5.18, 0.07, 0.07, 0.07]);\n' ...
        'psi = eta(6);\n' ...
        'R = [cos(psi) -sin(psi) 0; sin(psi) cos(psi) 0; 0 0 1];\n' ...
        'v_world = R * nu(1:3);\n' ...
        'f_world = 32.0 * (v_des - v_world);\n' ...
        'f_body = R'' * f_world;\n' ...
        'yaw_des = atan2(target(2)-p(2), target(1)-p(1));\n' ...
        'e_yaw = atan2(sin(yaw_des - psi), cos(yaw_des - psi));\n' ...
        'tau = [max(min(f_body, 40), -40); -8*eta(4)-2.5*nu(4); -8*eta(5)-2.5*nu(5); 10*e_yaw-3.5*nu(6)];\n' ...
        'nu_dot = M \\ (tau - D * nu);\n' ...
        'nu_next = nu + dt * nu_dot;\n' ...
        'eta_next = eta + dt * [R * nu_next(1:3); nu_next(4:6)];\n' ...
        'eta_next(3) = max(min(eta_next(3), -0.5), -28.0);\n' ...
        'state_next = [eta_next; nu_next];\n' ...
        'end\n']);
end

function s = hider_fcn_code()
    s = sprintf([ ...
        'function state_next = stepHider(t, state_prev, seeker_state)\n' ...
        '%% 6-DOF Hider Evasion AI + Fossen Hydrodynamics (dt = 0.05s)\n' ...
        'dt = 0.05;\n' ...
        'eta = state_prev(1:6); nu = state_prev(7:12);\n' ...
        'p_h = eta(1:3); p_s = seeker_state(1:3);\n' ...
        'away = p_h - p_s;\n' ...
        'n = norm(away);\n' ...
        'if n > 1e-3, dir = away / n; else, dir = [-1; -1; 0]; end\n' ...
        'dir = dir + 0.45 * [-dir(2); dir(1); 0] * sin(0.35 * t);\n' ...
        'v_des = (dir / max(1e-3, norm(dir))) * 1.45;\n' ...
        '%% Boundary repulsion\n' ...
        'if p_h(1) < -50, v_des(1) = abs(v_des(1)); end\n' ...
        'if p_h(1) >  50, v_des(1) = -abs(v_des(1)); end\n' ...
        'if p_h(2) < -50, v_des(2) = abs(v_des(2)); end\n' ...
        'if p_h(2) >  50, v_des(2) = -abs(v_des(2)); end\n' ...
        'M = diag([17.0, 24.2, 26.07, 0.28, 0.28, 0.40]);\n' ...
        'D = diag([4.03, 6.22, 5.18, 0.07, 0.07, 0.07]);\n' ...
        'psi = eta(6);\n' ...
        'R = [cos(psi) -sin(psi) 0; sin(psi) cos(psi) 0; 0 0 1];\n' ...
        'v_world = R * nu(1:3);\n' ...
        'f_body = R'' * (30.0 * (v_des - v_world));\n' ...
        'yaw_des = atan2(v_des(2), v_des(1));\n' ...
        'e_yaw = atan2(sin(yaw_des - psi), cos(yaw_des - psi));\n' ...
        'tau = [max(min(f_body, 35), -35); -8*eta(4)-2.5*nu(4); -8*eta(5)-2.5*nu(5); 10*e_yaw-3.5*nu(6)];\n' ...
        'nu_dot = M \\ (tau - D * nu);\n' ...
        'nu_next = nu + dt * nu_dot;\n' ...
        'eta_next = eta + dt * [R * nu_next(1:3); nu_next(4:6)];\n' ...
        'eta_next(3) = max(min(eta_next(3), -1.0), -27.0);\n' ...
        'state_next = [eta_next; nu_next];\n' ...
        'end\n']);
end

function s = ekf_fcn_code()
    s = sprintf([ ...
        'function ekf_next = stepEKF(seeker_state, hider_state, ekf_prev)\n' ...
        '%% Sonar Measurement + Alpha-Beta / EKF Target Tracker\n' ...
        'dt = 0.05;\n' ...
        'p_s = seeker_state(1:3); p_h = hider_state(1:3);\n' ...
        'pos_pred = ekf_prev(1:3) + dt * ekf_prev(4:6);\n' ...
        'vel_pred = 0.98 * ekf_prev(4:6);\n' ...
        'dist = norm(p_h - p_s);\n' ...
        'if dist <= 55.0\n' ...
        '    alpha = 0.35; beta = 0.15;\n' ...
        '    innov = p_h - pos_pred;\n' ...
        '    pos_upd = pos_pred + alpha * innov;\n' ...
        '    vel_upd = vel_pred + (beta / dt) * innov * 0.1;\n' ...
        '    ekf_next = [pos_upd; vel_upd];\n' ...
        'else\n' ...
        '    ekf_next = [pos_pred; vel_pred];\n' ...
        'end\n' ...
        'end\n']);
end

function s = capture_fcn_code()
    s = sprintf([ ...
        'function [dist, captured] = monitorCapture(t, seeker_state, hider_state)\n' ...
        'dist = norm(seeker_state(1:3) - hider_state(1:3));\n' ...
        'captured = double(t >= 8.0 && dist <= 3.0);\n' ...
        'end\n']);
end
